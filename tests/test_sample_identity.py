from pathlib import Path

import pytest

from genokeeper.config import load_grading
from genokeeper.sample_identity import (
    DELIVERED_HEADER,
    NO_CALL,
    NOT_DELIVERED,
    NOT_SNV,
    OTHER_ALLELE,
    PALINDROMIC,
    UNKNOWN,
    Identity,
    Verdict,
    compare,
    find_delivered,
    judge,
    read_delivered,
)


def test_concordant_and_discordant() -> None:
    delivered = {"rs1": "AG", "rs2": "CC", "rs3": "GG"}
    ours = [
        ("rs1", "A", "G", "1"),
        ("rs2", "C", "T", "0"),
        ("rs3", "G", "T", "2"),  # ours TT, delivered GG
    ]
    identity = compare(delivered, ours)
    assert (identity.compared, identity.concordant) == (3, 2)
    assert identity.concordance == pytest.approx(2 / 3)


def test_complement_counts_palindrome_skipped() -> None:
    identity = compare(
        {"rs1": "TC", "rs2": "AT"},
        [("rs1", "A", "G", "1"), ("rs2", "A", "T", "1")],
    )
    assert (identity.compared, identity.concordant) == (1, 1)
    assert identity.skipped == {PALINDROMIC: 1}


def test_skips_by_reason() -> None:
    delivered = {"rs1": "--", "rs2": "DI", "rs3": "AC", "rs4": "AG"}
    ours = [
        ("rs1", "A", "G", "1"),
        ("rs2", "A", "G", "1"),
        ("rs3", "A", "G", "1"),
        ("rs4", "A", "G", "unknown"),
        ("rs5", "A", "G", "1"),
        ("rs1", "A", "G", "0"),  # a second row of one rsID: the first is kept
    ]
    identity = compare(delivered, ours)
    assert identity.compared == 0
    assert identity.concordance == 0.0
    assert identity.skipped == {
        NO_CALL: 1,
        NOT_SNV: 1,
        OTHER_ALLELE: 1,
        UNKNOWN: 1,
        NOT_DELIVERED: 1,
    }


def _delivered(path: Path, rows: list[str], header: str = DELIVERED_HEADER) -> Path:
    lines = ["# This data file generated by a lab", header, *rows]
    path.write_text("\n".join(lines) + "\n")
    return path


def test_reader_keeps_autosomal_rsids(tmp_path: Path) -> None:
    path = _delivered(
        tmp_path / "genome.txt",
        [
            "rs1\t1\t100\tAG",
            "rs2\t22\t200\tcc",
            "rs3\tX\t300\tA",
            "rs4\tMT\t400\tG",
            "i5001\t3\t500\tTT",
            "rs5\tY\t600\tC",
        ],
    )
    assert read_delivered(path) == {"rs1": "AG", "rs2": "CC"}


def test_find_delivered_skips_vc_txt(tmp_path: Path) -> None:
    _delivered(tmp_path / "sample.vc.txt", ["rs1\t1\t100\tAG"])
    assert find_delivered(tmp_path) is None
    delivered = _delivered(tmp_path / "sample.txt", ["rs1\t1\t100\tAG"])
    assert find_delivered(tmp_path) == delivered
    assert find_delivered(tmp_path / "absent") is None


def test_find_delivered_refuses_two(tmp_path: Path) -> None:
    _delivered(tmp_path / "a.txt", ["rs1\t1\t100\tAG"])
    _delivered(tmp_path / "b.txt", ["rs1\t1\t100\tAG"])
    with pytest.raises(ValueError, match=r"a\.txt.*b\.txt"):
        find_delivered(tmp_path)


def test_find_delivered_ignores_other_txt(tmp_path: Path) -> None:
    delivered = _delivered(tmp_path / "sample.txt", ["rs1\t1\t100\tAG"])
    (tmp_path / "notes.txt").write_text("# my notes\nrs1 is interesting\n")
    # The column line after the first data row is not the header.
    (tmp_path / "late.txt").write_text(f"rs1\t1\t100\tAG\n{DELIVERED_HEADER}\n")
    assert find_delivered(tmp_path) == delivered


def _identity(compared: int, concordant: int) -> Identity:
    return Identity(compared=compared, concordant=concordant, skipped={})


def test_judge_thresholds() -> None:
    t = load_grading().identity
    verdict, text = judge(_identity(999, 999), t)
    assert verdict is Verdict.NOT_CHECKED
    assert "999 compared" in text
    verdict, text = judge(_identity(1000, 979), t)
    assert verdict is Verdict.MISMATCH
    assert "0.979" in text and "1,000" in text
    assert text.startswith("the FASTQ does not match the delivered genotypes")
    verdict, text = judge(_identity(1000, 980), t)
    assert verdict is Verdict.MATCHED
    assert text == "1,000 SNPs, concordance 0.9800"
